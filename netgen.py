#!/usr/bin/env python3
"""
netgen.py - generate Docker Compose network topology from x-net annotations.

Reads one or more compose files, looks at each service's `x-net` block, and
writes an override file next to each one (compose.yml -> compose.netgen.yml)
that defines one small network per relationship and attaches each service only
to the networks it needs. Services in different files can reference each other.

Annotations (all optional, per service):

    x-net:
      role: proxy          # the reverse proxy (exactly one across all files)
      role: vpn            # a VPN gateway like gluetun that other containers
                           # sit behind (auto-detected from a gluetun image)
      web: true            # reachable through the proxy -> proxy_<svc> network
      talks_to: [db, redis:6379]   # opens connections to these services
                                   # (service names, not container_name)
      internal: true       # no internet access (no egress network)

Unknown keys are an error, so a typo like `talk_to` doesn't silently do nothing.

Rules:
  * web: true           -> network proxy_<svc>, members: proxy + svc
  * talks_to: [x]       -> network link_<a>__<b> (names sorted, so A->B and
                           B->A share one), members: both services
  * not internal        -> network egress_<svc>, members: svc only.
                           This is the only non-internal network a service
                           gets, so internet access and published ports are
                           opt-out per service.
  * every generated network except egress_* is `internal: true`.
  * services with no x-net block are left untouched (Compose default network).

Shared network stacks (network_mode: "service:<parent>", e.g. gluetun):
  * a service behind a parent has no networks of its own, so its x-net is
    merged into the parent's: web/talks_to on qbittorrent become networks on
    gluetun, and talks_to: [qbittorrent] elsewhere links to gluetun.
    Other services reach it at the parent's name (gluetun:8080).
  * services behind the same parent share localhost; talks_to between them
    is skipped.
  * gluetun answers DNS itself and cannot resolve container names, so for
    every link gluetun is on, the other end gets a fixed IP and gluetun gets
    an extra_hosts entry for it. Containers behind gluetun share that hosts
    file, so `prowlarr -> sonarr` resolves.
  * gluetun cannot be internal: it needs egress to reach the VPN server.

Networks whose members all live in one file are ordinary project networks.
Networks that span files are named `netgen_<network>` and marked
`external: true`; run with --apply to create them before `docker compose up`.

Subnets are allocated as /24s from --base and kept in net.lock, so adding a
service never renumbers existing networks. Service names must be unique
across all files.

Usage:
    python3 netgen.py -f proxy/compose.yml -f immich/compose.yml
    python3 netgen.py -f ... --apply      # also create shared networks
    python3 netgen.py -f ... --check      # exit 1 if any output is stale
    python3 netgen.py -f ... --prune      # release subnets of removed networks

After writing, netgen prints the `docker compose ... up -d` command for every
file you passed (with its override where there is one), ready to paste.

netgen also sets COMPOSE_FILE=<file>:<override> in each project's .env, so
plain `docker compose up -d`, `logs`, `down` etc. in that folder pick up the
override. Only that one line is touched; other files you already list in
COMPOSE_FILE are kept. Use --no-env to skip this.
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import os
import shlex
import subprocess
import sys
from pathlib import Path

import yaml

HEADER = (
    "# GENERATED by netgen.py from {src} - do not edit by hand.\n"
    "# This is an OVERRIDE file: it only adds networks. Use it together with {src}:\n"
    "#   docker compose -f {src} -f {out} up -d\n"
    "# or put COMPOSE_FILE={src}:{out} in .env\n"
)
SHARED_HEADER = (
    "# Networks marked external are shared with other compose files.\n"
    "# Create them first with: netgen.py ... --apply\n"
)
SHARED_PREFIX = "netgen_"
PIN_OFFSET = 10  # fixed IPs on gluetun links start at .10
ROLES = ("proxy", "vpn")
KNOWN_KEYS = {"role", "web", "talks_to", "internal"}


def fail(msg: str) -> None:
    sys.exit(f"netgen: error: {msg}")


def warn(msg: str) -> None:
    print(f"netgen: warning: {msg}", file=sys.stderr)


def override_path(src: Path) -> Path:
    return src.with_name(f"{src.stem}.netgen.yml")


def load_all(paths: list[Path]) -> tuple[dict, dict]:
    """Return (services, origin): every service across files, and service -> file."""
    services, origin = {}, {}
    for path in paths:
        if not path.exists():
            fail(f"{path} not found")
        data = yaml.safe_load(path.read_text()) or {}
        for name, spec in (data.get("services") or {}).items():
            if name in services:
                fail(f"service '{name}' is defined in both {origin[name]} and {path}; "
                     "service names must be unique across files")
            services[name], origin[name] = spec or {}, path
    if not services:
        fail("no services found")
    return services, origin


def resolve_parents(services: dict, origin: dict) -> dict:
    """Map every service to the service that owns its network stack."""
    parent = {}
    for name, spec in services.items():
        mode = spec.get("network_mode")
        if isinstance(mode, str) and mode.startswith("service:"):
            p = mode.split(":", 1)[1]
            if p not in services:
                fail(f"{name}: network_mode points at unknown service '{p}'")
            if origin[p] != origin[name]:
                fail(f"{name}: network_mode service:{p} must be in the same compose file")
            parent[name] = p

    def root(name: str, seen: tuple = ()) -> str:
        if name in seen:
            fail(f"network_mode cycle: {' -> '.join(seen + (name,))}")
        return root(parent[name], seen + (name,)) if name in parent else name

    return {name: root(name) for name in services}


def merge_annotations(services: dict, owner: dict) -> tuple[dict, dict]:
    """Fold x-net from services behind a parent into the parent.

    Returns (merged, members): root -> merged x-net, root -> [root, *behind it].
    """
    merged: dict[str, dict] = {}
    members: dict[str, list] = {}
    for name in services:
        members.setdefault(owner[name], [owner[name]])
        if owner[name] != name:
            members[owner[name]].append(name)

    for name, spec in services.items():
        if "x-net" not in spec:
            continue
        ann = spec.get("x-net") or {}
        r = owner[name]
        mode = spec.get("network_mode")
        if mode and r == name:
            fail(f"{name}: has network_mode: {mode} and x-net; only "
                 "network_mode: service:<name> can be combined with x-net")
        if not isinstance(ann, dict):
            fail(f"{name}: x-net must be a mapping, e.g. x-net: {{}}")
        if "vpn" in ann:
            fail(f"{name}: 'vpn: true' is now 'role: vpn'")
        unknown = set(ann) - KNOWN_KEYS
        if unknown:
            fail(f"{name}: unknown x-net key(s): {', '.join(sorted(unknown))} "
                 f"(expected {', '.join(sorted(KNOWN_KEYS))})")
        if ann.get("role") not in (None, *ROLES):
            fail(f"{name}: unknown role '{ann['role']}' (expected {' or '.join(ROLES)})")
        m = merged.setdefault(r, {"talks_to": [], "web": False, "internal": False,
                                  "role": None, "vpn": False, "web_from": []})
        if r != name:
            for key in ("internal", "role"):
                if ann.get(key):
                    fail(f"{name}: '{key}' must be set on {r}, which owns its network stack")
            if spec.get("ports"):
                fail(f"{name}: move its ports to {r}; it shares {r}'s network stack")
        else:
            m["internal"] = bool(ann.get("internal"))
            m["role"] = ann.get("role")
        if ann.get("web"):
            m["web"] = True
            m["web_from"].append(name)
        m["talks_to"] += [(name, str(t)) for t in ann.get("talks_to") or []]

    for r, m in merged.items():
        image = str(services[r].get("image", ""))
        if m["role"] is None and "gluetun" in image:
            m["role"] = "vpn"
        m["vpn"] = m["role"] == "vpn"
        if m["vpn"] and m["internal"]:
            fail(f"{r}: role: vpn cannot be internal; it needs egress to reach the VPN server")
    return merged, members


def build_topology(services: dict, owner: dict, merged: dict) -> tuple[dict, dict, dict, list]:
    """Return (networks, attachments, links, notes).

    networks:    name -> {"internal": bool, "purpose": str}
    attachments: root service -> sorted list of network names
    links:       link network -> (a, b) roots
    """
    proxies = [n for n, a in merged.items() if a["role"] == "proxy"]
    if len(proxies) > 1:
        fail(f"more than one service has role: proxy ({', '.join(proxies)})")
    proxy = proxies[0] if proxies else None

    networks: dict[str, dict] = {}
    attach: dict[str, set] = {n: set() for n in merged}
    links: dict[str, tuple] = {}
    notes: list[str] = []

    def add(net: str, internal: bool, purpose: str, *nodes: str) -> None:
        networks.setdefault(net, {"internal": internal, "purpose": purpose})
        for n in nodes:
            attach.setdefault(n, set()).add(net)

    for r, ann in list(merged.items()):
        if services[r].get("networks"):
            warn(f"{r} already lists networks in its compose file; "
                 "they will be merged with the generated ones")

        if ann["web"]:
            if not proxy:
                fail(f"{r}: web: true but no service has role: proxy")
            if r == proxy:
                fail(f"{r}: the proxy cannot also be web: true")
            add(f"proxy_{r}", True, f"{proxy} -> {r}", proxy, r)
            for svc in ann["web_from"]:
                if svc != r:
                    notes.append(f"{svc} is behind {r}: point the proxy at {r}:<port>")

        for src, target in ann["talks_to"]:
            dep = target.split(":", 1)[0]
            if dep not in services:
                fail(f"{src}: talks_to unknown service '{dep}'")
            d = owner[dep]
            if d == r:
                if dep != src:
                    notes.append(f"{src} -> {dep}: same network stack, use localhost")
                continue
            if d not in merged:
                merged[d] = {"talks_to": [], "web": False, "internal": False,
                             "role": None, "vpn": False, "web_from": []}
                attach.setdefault(d, set())
                warn(f"{src}: talks_to '{dep}', which has no x-net; it will be "
                     "attached to the link but gets no other generated networks")
            if d != dep:
                notes.append(f"{src} -> {dep}: {dep} is behind {d}, connect to {d}:<port>")
            a, b = sorted((r, d))
            net = f"link_{a}__{b}"
            add(net, True, f"{a} <-> {b}", a, b)
            links[net] = (a, b)

        if not ann["internal"]:
            add(f"egress_{r}", False, f"{r} -> internet / published ports", r)
        elif services[r].get("ports"):
            fail(f"{r}: internal: true but publishes ports; published ports "
                 "need a non-internal network")

    return networks, {s: sorted(n) for s, n in attach.items() if n}, links, notes


def host_names(svc: str, services: dict) -> list:
    """Names an app might use for svc: service name, plus container_name if set."""
    cn = services[svc].get("container_name")
    return [svc] + ([cn] if cn and cn != svc else [])


def pin_addresses(links: dict, merged: dict, members: dict, lock: dict,
                  services: dict) -> tuple[dict, dict]:
    """Fixed IPs + extra_hosts so gluetun can resolve what it links to.

    Returns (pins, hosts): (service, network) -> ip, gluetun root -> [host:ip].
    """
    pins: dict[tuple, str] = {}
    hosts: dict[str, list] = {}
    for net, (a, b) in sorted(links.items()):
        subnet = ipaddress.ip_network(lock[net])
        for i, (me, other) in enumerate(((a, b), (b, a))):
            if not merged[me]["vpn"]:
                continue
            key = (other, net)
            if key not in pins:
                pins[key] = str(subnet.network_address + PIN_OFFSET + i)
            for svc in members.get(other, [other]):
                for alias in host_names(svc, services):
                    hosts.setdefault(me, []).append(f"{alias}:{pins[key]}")
    return pins, {k: sorted(set(v)) for k, v in hosts.items()}


def shared_networks(networks: dict, attach: dict, origin: dict) -> set:
    """Networks whose members come from more than one compose file."""
    files: dict[str, set] = {n: set() for n in networks}
    for svc, nets in attach.items():
        for n in nets:
            files[n].add(origin[svc])
    return {n for n, f in files.items() if len(f) > 1}


def allocate(networks: dict, lock: dict, base: str, prune: bool) -> dict:
    pool = ipaddress.ip_network(base)
    if pool.prefixlen > 24:
        fail(f"--base {base} is smaller than a /24")
    if prune:
        lock = {n: s for n, s in lock.items() if n in networks}
    used = {ipaddress.ip_network(s) for s in lock.values()}
    free = (s for s in pool.subnets(new_prefix=24) if s not in used)
    for name in sorted(networks):
        if name not in lock:
            try:
                lock[name] = str(next(free))
            except StopIteration:
                fail(f"address pool {base} exhausted; use a bigger --base")
    return dict(sorted(lock.items()))


def network_def(name: str, spec: dict, subnet: str, shared: bool) -> dict:
    if shared:
        return {"name": SHARED_PREFIX + name, "external": True}
    return {
        **({"internal": True} if spec["internal"] else {}),
        "ipam": {"config": [{"subnet": subnet}]},
        "labels": {"netgen.purpose": spec["purpose"]},
    }


def service_def(svc: str, nets: list, pins: dict, hosts: dict) -> dict:
    if any((svc, n) in pins for n in nets):
        out = {"networks": {n: ({"ipv4_address": pins[(svc, n)]} if (svc, n) in pins else {})
                            for n in nets}}
    else:
        out = {"networks": nets}
    if svc in hosts:
        out["extra_hosts"] = hosts[svc]
    return out


def render(src: Path, networks: dict, attach: dict, lock: dict, origin: dict,
           shared: set, pins: dict, hosts: dict) -> str | None:
    """Override for one compose file, or None if it has no annotated services."""
    mine = {s: nets for s, nets in sorted(attach.items()) if origin[s] == src}
    if not mine:
        return None
    used = sorted({n for nets in mine.values() for n in nets})
    doc = {
        "services": {s: service_def(s, nets, pins, hosts) for s, nets in mine.items()},
        "networks": {n: network_def(n, networks[n], lock[n], n in shared) for n in used},
    }
    header = HEADER.format(src=src.name, out=override_path(src).name)
    if shared & set(used):
        header += SHARED_HEADER
    return header + yaml.safe_dump(doc, sort_keys=False, width=100)


def apply_shared(shared: set, networks: dict, lock: dict) -> None:
    """Create missing shared networks; warn if an existing one doesn't match."""
    for name in sorted(shared):
        docker_name, spec, subnet = SHARED_PREFIX + name, networks[name], lock[name]
        probe = subprocess.run(["docker", "network", "inspect", docker_name],
                               capture_output=True, text=True)
        if probe.returncode == 0:
            info = json.loads(probe.stdout)[0]
            have = [c.get("Subnet") for c in (info.get("IPAM") or {}).get("Config") or []]
            if subnet not in have or bool(info.get("Internal")) != spec["internal"]:
                warn(f"{docker_name} exists but differs (subnet {have}, "
                     f"internal={info.get('Internal')}); expected {subnet}, "
                     f"internal={spec['internal']}. Remove it and re-run --apply.")
            continue
        cmd = ["docker", "network", "create", "--driver", "bridge", "--subnet", subnet,
               "--label", f"netgen.purpose={spec['purpose']}"]
        if spec["internal"]:
            cmd.append("--internal")
        subprocess.run(cmd + [docker_name], check=True, stdout=subprocess.DEVNULL)
        print(f"created {docker_name} ({subnet})")


def label(svc: str, members: dict) -> str:
    behind = members.get(svc, [svc])[1:]
    return f"{svc}[{','.join(sorted(behind))}]" if behind else svc


def summary(networks: dict, attach: dict, lock: dict, shared: set, members: dict) -> str:
    lines = [f"{'network':<34} {'subnet':<17} {'internal':<9} {'shared':<7} members"]
    for name, spec in sorted(networks.items()):
        nodes = ", ".join(label(s, members) for s, nets in sorted(attach.items()) if name in nets)
        lines.append(f"{name:<34} {lock[name]:<17} {str(spec['internal']).lower():<9} "
                     f"{'yes' if name in shared else '':<7} {nodes}")
    return "\n".join(lines)


def update_env(src: Path, has_override: bool) -> str | None:
    """Keep COMPOSE_FILE in the project's .env pointing at src + its override.

    Only the COMPOSE_FILE line is touched; other entries already in it (extra
    overrides you added) are kept. Returns a short description of the change.
    """
    env = src.parent / ".env"
    lines = env.read_text().splitlines() if env.exists() else []
    idx = next((i for i, l in enumerate(lines)
                if l.strip().startswith("COMPOSE_FILE=")), None)
    current = lines[idx].split("=", 1)[1].strip().strip("'\"").split(":") if idx is not None else []
    current = [c for c in current if c]
    ovr = override_path(src).name

    others = [c for c in current if c not in (src.name, ovr)]
    if has_override:
        wanted = [src.name, *others, ovr]
    elif others:
        wanted = [src.name, *others]   # keep your extra overrides, drop ours
    else:
        wanted = []                    # nothing left worth a COMPOSE_FILE line

    if wanted == current:
        return None
    if not wanted and (idx is None or ovr not in current):
        return None                    # never remove a line we didn't write
    new = f"COMPOSE_FILE={':'.join(wanted)}" if wanted else None
    if idx is None:
        lines.append(new)
    elif new is None:
        del lines[idx]
    else:
        lines[idx] = new
    env.write_text("\n".join(lines) + ("\n" if lines else ""))
    return f"{env}: {new or 'removed COMPOSE_FILE'}"


def shell_path(p: Path) -> str:
    """Path as typed relative to the current directory, quoted for the shell."""
    rel = os.path.relpath(p)
    return shlex.quote(rel if not rel.startswith("../../") else str(p))


DEFAULT_NAMES = ("compose.yaml", "compose.yml", "docker-compose.yaml", "docker-compose.yml")


def is_default_file(p: Path) -> bool:
    """True if plain `docker compose` in p's folder would pick p by itself."""
    first = next((p.parent / n for n in DEFAULT_NAMES if (p.parent / n).exists()), None)
    return first == p


def env_targets(paths: list[Path]) -> set:
    """Files whose .env netgen may manage: one compose file per folder."""
    by_dir: dict[Path, list] = {}
    for p in paths:
        by_dir.setdefault(p.parent, []).append(p)
    ok = set()
    for d, ps in by_dir.items():
        if len(ps) > 1:
            warn(f"{d} holds several compose files ({', '.join(x.name for x in ps)}); "
                 "not touching its .env, pass these with -f instead")
        else:
            ok.add(ps[0])
    return ok


def up_commands(paths: list[Path], outputs: dict, shared: set, applied: bool,
                env: set) -> list[str]:
    """Copy-pastable commands to bring every project up with its override.

    With COMPOSE_FILE in each .env, a plain `docker compose up -d` in the
    project folder is enough; otherwise list the files explicitly.
    """
    cmds = []
    if shared and not applied:
        argv = [a for a in sys.argv[1:] if a not in ("-q", "--quiet")]
        cmds.append(shlex.join(["python3", sys.argv[0], *argv, "--apply"]))
    for p in paths:
        if p in env and (outputs.get(override_path(p)) is not None or is_default_file(p)):
            cmds.append(f"(cd {shell_path(p.parent)} && docker compose up -d)")
            continue
        files = ["-f", shell_path(p)]
        out = override_path(p)
        if outputs.get(out) is not None:
            files += ["-f", shell_path(out)]
        cmds.append(" ".join(["docker", "compose", *files, "up", "-d"]))
    return cmds


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("-f", "--file", action="append", type=Path,
                    help="compose file (repeatable; default compose.yml)")
    ap.add_argument("--lock", default="net.lock", type=Path)
    ap.add_argument("--base", default="10.200.0.0/16", help="pool to carve /24s from")
    ap.add_argument("--check", action="store_true", help="exit 1 if any output is stale")
    ap.add_argument("--apply", action="store_true", help="create shared networks in Docker")
    ap.add_argument("--prune", action="store_true", help="drop lock entries for removed networks")
    ap.add_argument("--no-env", dest="env", action="store_false",
                    help="don't set COMPOSE_FILE in each project's .env")
    ap.add_argument("-q", "--quiet", action="store_true")
    args = ap.parse_args()

    paths = [p.resolve() for p in (args.file or [Path("compose.yml")])]
    services, origin = load_all(paths)
    owner = resolve_parents(services, origin)
    merged, members = merge_annotations(services, owner)
    networks, attach, links, notes = build_topology(services, owner, merged)
    shared = shared_networks(networks, attach, origin)
    lock_in = json.loads(args.lock.read_text()) if args.lock.exists() else {}
    lock = allocate(networks, dict(lock_in), args.base, args.prune)
    pins, hosts = pin_addresses(links, merged, members, lock, services)
    outputs = {override_path(p): render(p, networks, attach, lock, origin, shared, pins, hosts)
               for p in paths}

    if args.check:
        stale = [str(out) for out, text in outputs.items()
                 if (out.read_text() if out.exists() else None) != text]
        if lock != lock_in:
            stale.append(str(args.lock))
        for s in stale:
            print(f"netgen: {s} is out of date; run netgen.py", file=sys.stderr)
        sys.exit(1 if stale else 0)

    for out, text in outputs.items():
        if text is None:
            if out.exists():
                out.unlink()
            continue
        out.write_text(text)
    args.lock.write_text(json.dumps(lock, indent=2) + "\n")
    env_paths = env_targets(paths) if args.env else set()
    env_changes = [c for p in paths if p in env_paths
                   if (c := update_env(p, outputs[override_path(p)] is not None))]

    if not args.quiet:
        print(summary(networks, attach, lock, shared, members))
        for n in sorted(set(notes)):
            print(f"note: {n}")
        written = [str(o) for o, t in outputs.items() if t is not None]
        print(f"\nwrote {', '.join(written)} and {args.lock}")
        for c in env_changes:
            print(f"updated {c}")
    if args.apply:
        apply_shared(shared, networks, lock)
    if not args.quiet:
        print("\nto start everything:\n")
        print("\n".join(up_commands(paths, outputs, shared, args.apply, env_paths)))


if __name__ == "__main__":
    main()